create extension if not exists pgcrypto with schema extensions;

-- ------------------------------------------------------------
-- 1) Cuentas: solo usuario y contraseña (sin correo).
--    La contraseña se guarda cifrada con bcrypt.
--    Nadie puede leer estas tablas desde la app: solo las funciones de abajo.
-- ------------------------------------------------------------
create table if not exists public.usuarios (
  id         uuid primary key default gen_random_uuid(),
  usuario    text not null check (usuario ~ '^[A-Za-z0-9_ñÑáéíóúÁÉÍÓÚüÜ]{3,16}$'),
  hash       text not null,
  creado_en  timestamptz not null default now()
);
create unique index if not exists usuarios_usuario_unico on public.usuarios (lower(usuario));

create table if not exists public.sesiones (
  token      uuid primary key default gen_random_uuid(),
  usuario_id uuid not null references public.usuarios (id) on delete cascade,
  creado_en  timestamptz not null default now(),
  expira     timestamptz not null default now() + interval '30 days'
);

alter table public.usuarios enable row level security;
alter table public.sesiones enable row level security;
revoke all on public.usuarios, public.sesiones from anon, authenticated;

-- ------------------------------------------------------------
-- 2) Partidas (cada fila es una batalla terminada)
-- ------------------------------------------------------------
create table if not exists public.partidas (
  id            bigint generated by default as identity primary key,
  jugador       text        not null check (char_length(jugador) between 2 and 20),
  rival_nombre  text        check (char_length(rival_nombre) <= 40),
  generacion    text        not null check (char_length(generacion) <= 40),
  resultado     text        not null check (resultado in ('victoria', 'derrota')),
  turnos        int         not null default 0 check (turnos between 0 and 999),
  restantes     int         not null default 0 check (restantes between 0 and 6),
  tamano        int         not null default 6 check (tamano in (3, 6)),
  mvp_id        int         check (mvp_id between 1 and 1100),
  mvp_nombre    text        check (char_length(mvp_nombre) <= 40),
  equipo        jsonb       not null default '[]'::jsonb,
  rival         jsonb       not null default '[]'::jsonb,
  creado_en     timestamptz not null default now()
);
alter table public.partidas add column if not exists modo text not null default 'cpu' check (modo in ('cpu', 'pvp'));
alter table public.partidas add column if not exists usuario_id uuid references public.usuarios (id) on delete set null;

create index if not exists partidas_creado_en_idx on public.partidas (creado_en desc);
create index if not exists partidas_jugador_idx   on public.partidas (jugador);

alter table public.partidas enable row level security;

drop policy if exists "partidas: lectura publica" on public.partidas;
create policy "partidas: lectura publica"
  on public.partidas for select
  to anon, authenticated
  using (true);

-- Ya no se inserta directo: solo con la función guardar_partida (requiere sesión)
drop policy if exists "partidas: registrar batalla" on public.partidas;
revoke insert, update, delete on public.partidas from anon, authenticated;
grant select on public.partidas to anon, authenticated;

-- ------------------------------------------------------------
-- 3) Funciones de la app (se llaman con supabase.rpc)
-- ------------------------------------------------------------
create or replace function public.registrar(p_usuario text, p_password text)
returns json language plpgsql security definer set search_path = public as $$
declare v_id uuid; v_token uuid; v_usuario text := trim(p_usuario);
begin
  if v_usuario !~ '^[A-Za-z0-9_ñÑáéíóúÁÉÍÓÚüÜ]{3,16}$' then raise exception 'USUARIO_INVALIDO'; end if;
  if char_length(p_password) < 4 or char_length(p_password) > 72 then raise exception 'PASSWORD_INVALIDA'; end if;
  if exists (select 1 from usuarios where lower(usuario) = lower(v_usuario)) then raise exception 'USUARIO_EXISTE'; end if;
  insert into usuarios (usuario, hash) values (v_usuario, extensions.crypt(p_password, extensions.gen_salt('bf', 8)))
    returning id into v_id;
  insert into sesiones (usuario_id) values (v_id) returning token into v_token;
  return json_build_object('token', v_token, 'usuario', v_usuario);
end $$;

create or replace function public.iniciar_sesion(p_usuario text, p_password text)
returns json language plpgsql security definer set search_path = public as $$
declare v_id uuid; v_usuario text; v_hash text; v_token uuid;
begin
  select id, usuario, hash into v_id, v_usuario, v_hash from usuarios where lower(usuario) = lower(trim(p_usuario));
  if not found or extensions.crypt(p_password, v_hash) <> v_hash then raise exception 'CREDENCIALES'; end if;
  delete from sesiones where usuario_id = v_id and expira < now();
  insert into sesiones (usuario_id) values (v_id) returning token into v_token;
  return json_build_object('token', v_token, 'usuario', v_usuario);
end $$;

create or replace function public.sesion_actual(p_token uuid)
returns json language sql security definer set search_path = public as $$
  select json_build_object('usuario', u.usuario)
  from sesiones s join usuarios u on u.id = s.usuario_id
  where s.token = p_token and s.expira > now();
$$;

create or replace function public.cerrar_sesion(p_token uuid)
returns void language sql security definer set search_path = public as $$
  delete from sesiones where token = p_token;
$$;

create or replace function public.guardar_partida(p_token uuid, p jsonb)
returns void language plpgsql security definer set search_path = public as $$
declare v_id uuid; v_usuario text;
begin
  select u.id, u.usuario into v_id, v_usuario
  from sesiones s join usuarios u on u.id = s.usuario_id
  where s.token = p_token and s.expira > now();
  if not found then raise exception 'SESION_INVALIDA'; end if;
  insert into partidas (jugador, usuario_id, rival_nombre, generacion, resultado, turnos, restantes, tamano,
                        mvp_id, mvp_nombre, equipo, rival, modo)
  values (v_usuario, v_id, left(p->>'rival_nombre', 40), left(p->>'generacion', 40), p->>'resultado',
          coalesce((p->>'turnos')::int, 0), coalesce((p->>'restantes')::int, 0), coalesce((p->>'tamano')::int, 6),
          (p->>'mvp_id')::int, left(p->>'mvp_nombre', 40), coalesce(p->'equipo', '[]'::jsonb),
          coalesce(p->'rival', '[]'::jsonb), coalesce(p->>'modo', 'cpu'));
end $$;

revoke all on function public.registrar(text, text), public.iniciar_sesion(text, text), public.sesion_actual(uuid),
  public.cerrar_sesion(uuid), public.guardar_partida(uuid, jsonb) from public;
grant execute on function public.registrar(text, text), public.iniciar_sesion(text, text), public.sesion_actual(uuid),
  public.cerrar_sesion(uuid), public.guardar_partida(uuid, jsonb) to anon, authenticated;

-- ------------------------------------------------------------
-- 4) Ranking (victorias, derrotas y % por jugador)
-- ------------------------------------------------------------
create or replace view public.ranking
with (security_invoker = true) as
select
  jugador,
  count(*) filter (where resultado = 'victoria')::int as victorias,
  count(*) filter (where resultado = 'derrota')::int  as derrotas,
  count(*)::int                                        as partidas,
  round(100.0 * count(*) filter (where resultado = 'victoria') / count(*), 1) as porcentaje,
  max(creado_en)                                       as ultima_partida
from public.partidas
group by jugador;

grant select on public.ranking to anon, authenticated;

